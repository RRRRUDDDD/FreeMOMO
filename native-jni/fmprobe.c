/* Positional reads on flagged fds consult the shadow position (kept equal to
 * the kernel offset: lseek copies the kernel result, served reads resync the
 * kernel position with lseek, pass-through reads advance it naturally). */
static ssize_t my_read(int fd, void* buf, size_t count) {
    if (g_in_hook || !g_real_read) return g_real_read ? g_real_read(fd, buf, count) : -1;
    if (fd < 0 || fd >= FD_TABLE_SLOTS || !g_fd_flag[fd]) return g_real_read(fd, buf, count);
    g_in_hook = 1;
    long long x = g_fd_pos[fd];
    ssize_t rc = serve_tail(fd, buf, count, x, "read");
    if (rc == -2) {
        rc = g_real_read(fd, buf, count);
        int saved = errno;
        if (LOG_BUDGET(g_fd_ptlog[fd], REDIRECT_PTLOG_MAX))
            emit("passthrough read fd=%d x=%#llx n=%zu = %zd%s", fd, x, count, rc,
                 err_suffix(rc >= 0, saved));
        errno = saved;
        if (rc > 0) g_fd_pos[fd] = x + rc;
        g_in_hook = 0;
        return rc;
    }
    if (rc > 0) {
        g_fd_pos[fd] = x + rc;
        if (g_real_lseek) g_real_lseek(fd, (off_t)(x + rc), SEEK_SET);
    }
    g_in_hook = 0;
    return rc;
}

