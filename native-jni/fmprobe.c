static jfieldID my_getstaticfieldid(JNIEnv* env, jclass c, const char* name, const char* sig) {
    char cn[96];
    jboolean p0 = (*env)->ExceptionCheck(env);
    if (!p0) class_name_of(env, c, cn, sizeof(cn));
    else snprintf(cn, sizeof(cn), "<pending>");
    if (!p0 && !strncmp(cn, "com.maimemo.", 12)) {
        log_p1_state(env, c, "gsfid");
        dump_payload_dex_once();
        /* r31: probe whether P1's class table can resolve Gson right now.
         * Any pending exception this raises is OURS — clear it before the
         * real call runs. */
        if (name && !strcmp(name, "gson")) {
            jclass g = g_real_findclass(env, "com/google/gson/Gson");
            jboolean gp = (*env)->ExceptionCheck(env);
            if (gp) (*env)->ExceptionClear(env);
            char gname[96] = "?";
            if (g && !gp) class_name_of(env, g, gname, sizeof(gname));
            char gld[224] = "?";
            if (g && !gp) loader_chain_of(env, g, gld, sizeof(gld));
            emit("gson probe: FindClass com/google/gson/Gson -> %s cls=%p name=%s "
                 "chain=%s pending_cleared=%d",
                 g ? "ok" : "FAIL", (void*)g, gname, gld, (int)gp);
        }
    }
    char ld[224];
    if (!p0) loader_chain_of(env, c, ld, sizeof(ld));
    else snprintf(ld, sizeof(ld), "<pending>");
    jfieldID r = g_real_getstaticfieldid(env, c, name, sig);
    if (!g_in_hook && LOG_BUDGET(g_idcall_logged, 1200)) {
        jboolean pending = (*env)->ExceptionCheck(env);
        emit("jni GetStaticFieldID cls=%s ld=%s \"%s\" \"%s\" -> %s pending=%d", cn, ld,
             name ? name : "(null)", sig ? sig : "(null)", r ? "ok" : "FAIL", (int)pending);
    }
    return r;
}

static void hook_env_findclass(JavaVM* vm) {
    JNIEnv* env = NULL;
    if ((*vm)->GetEnv(vm, (void**)&env, JNI_VERSION_1_6) != JNI_OK || !env || !*env) {
        emit("jni hook: GetEnv failed");
        return;
    }
    /* Slot indices from the real jni.h layout. */
    size_t off_find = (size_t)((char*)&(*env)->FindClass - (char*)(*env));
    size_t off_gmid = (size_t)((char*)&(*env)->GetMethodID - (char*)(*env));
    size_t off_gsmid = (size_t)((char*)&(*env)->GetStaticMethodID - (char*)(*env));
    size_t off_gfid = (size_t)((char*)&(*env)->GetFieldID - (char*)(*env));
    size_t off_gsfid = (size_t)((char*)&(*env)->GetStaticFieldID - (char*)(*env));
    void** table = (void**)*env;
    struct { size_t off; void* hook; void** real; const char* name; } slots[] = {
        {off_find, (void*)my_findclass, (void**)&g_real_findclass, "FindClass"},
        {off_gmid, (void*)my_getmethodid, (void**)&g_real_getmethodid, "GetMethodID"},
        {off_gsmid, (void*)my_getstaticmethodid, (void**)&g_real_getstaticmethodid,
         "GetStaticMethodID"},
        {off_gfid, (void*)my_getfieldid, (void**)&g_real_getfieldid, "GetFieldID"},
        {off_gsfid, (void*)my_getstaticfieldid, (void**)&g_real_getstaticfieldid,
         "GetStaticFieldID"},
    };
    for (size_t i = 0; i < sizeof(slots) / sizeof(slots[0]); ++i) {
        void** slot = (void**)((char*)table + slots[i].off);
        uintptr_t page = (uintptr_t)slot & ~(uintptr_t)(g_pagesize - 1);
        if (mprotect((void*)page, (size_t)g_pagesize, PROT_READ | PROT_WRITE) != 0) {
            int saved = errno;
            emit("jni hook: mprotect %s failed errno=%d", slots[i].name, saved);
            continue;
        }
        *slots[i].real = *slot;
        *slot = slots[i].hook;
        emit("jni hook: %s slot=%zu -> %p (was %p)", slots[i].name, slots[i].off / sizeof(void*),
             slots[i].hook, *slots[i].real);
    }
    /* Cache Class.getName/getClassLoader for resolution in the Get*ID hooks. */
    jclass ccls = g_real_findclass(env, "java/lang/Class");
    if (ccls) {
        g_cached_getname_mid =
            g_real_getmethodid(env, ccls, "getName", "()Ljava/lang/String;");
        g_cached_getclassloader_mid =
            g_real_getmethodid(env, ccls, "getClassLoader", "()Ljava/lang/ClassLoader;");
        emit("jni hook: Class.getName mid=%p getClassLoader mid=%p",
             (void*)g_cached_getname_mid, (void*)g_cached_getclassloader_mid);
    }
    /* r24: stable loader identity (Object.hashCode) and the parent chain
     * (ClassLoader.getParent) for the gson resolution investigation. */
    jclass objcls = g_real_findclass(env, "java/lang/Object");
    if (objcls) {
        g_cached_hashcode_mid = g_real_getmethodid(env, objcls, "hashCode", "()I");
        g_cached_tostring_mid =
            g_real_getmethodid(env, objcls, "toString", "()Ljava/lang/String;");
    }
    jclass clcls = g_real_findclass(env, "java/lang/ClassLoader");
    if (clcls)
        g_cached_getparent_mid =
            g_real_getmethodid(env, clcls, "getParent", "()Ljava/lang/ClassLoader;");
    emit("jni hook: hashCode mid=%p getParent mid=%p",
         (void*)g_cached_hashcode_mid, (void*)g_cached_getparent_mid);
    /* r31: reflection handles for the P1 DexPathList state dump. */
    jclass bdcls = g_real_findclass(env, "dalvik/system/BaseDexClassLoader");
    jclass dplcls = g_real_findclass(env, "dalvik/system/DexPathList");
    jclass elemcls = g_real_findclass(env, "dalvik/system/DexPathList$Element");
    jclass dfcls = g_real_findclass(env, "dalvik/system/DexFile");
    if (bdcls)
        g_cached_pathlist_fid =
            g_real_getfieldid(env, bdcls, "pathList", "Ldalvik/system/DexPathList;");
    if (dplcls)
        g_cached_dexelements_fid = g_real_getfieldid(
            env, dplcls, "dexElements", "[Ldalvik/system/DexPathList$Element;");
    if (elemcls) {
        g_cached_elem_dexfile_fid =
            g_real_getfieldid(env, elemcls, "dexFile", "Ldalvik/system/DexFile;");
        g_cached_elem_path_fid =
            g_real_getfieldid(env, elemcls, "path", "Ljava/io/File;");
    }
    if (dfcls)
        g_cached_cookie_fid =
            g_real_getfieldid(env, dfcls, "mCookie", "Ljava/lang/Object;");
    emit("p1 reflect: pathList=%p dexElements=%p dexFile=%p path=%p cookie=%p",
         (void*)g_cached_pathlist_fid, (void*)g_cached_dexelements_fid,
         (void*)g_cached_elem_dexfile_fid, (void*)g_cached_elem_path_fid,
         (void*)g_cached_cookie_fid);
}

