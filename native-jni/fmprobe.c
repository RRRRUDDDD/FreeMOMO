static off_t my_lseek(int fd, off_t offset, int whence) {
    if (g_in_hook || !g_real_lseek) return g_real_lseek ? g_real_lseek(fd, offset, whence) : -1;
    if (fd < 0 || fd >= FD_TABLE_SLOTS || !g_fd_flag[fd]) return g_real_lseek(fd, offset, whence);
    g_in_hook = 1;
    off_t rc = g_real_lseek(fd, offset, whence);
    int saved = errno;
    if (rc >= 0) {
        g_fd_pos[fd] = (long long)rc;
        emit("lseek fd=%d off=%#llx whence=%d = %#llx from=\"%s\"", fd,
             (unsigned long long)offset, whence, (long long)rc, describe_fd(fd));
    } else {
        emit("lseek fd=%d off=%#llx whence=%d = -1 errno=%d", fd, (unsigned long long)offset,
             whence, saved);
    }
    errno = saved;
    g_in_hook = 0;
    return rc;
}

static void* my_mmap(void* addr, size_t length, int prot, int map_flags, int fd, off_t offset) {
    if (g_in_hook || !g_real_mmap) {
        return g_real_mmap ? g_real_mmap(addr, length, prot, map_flags, fd, offset) : MAP_FAILED;
    }
    /* Flagged fds map the ORIGIN apk instead: a shell-side mapping of
     * base.apk must show official bytes, and with the fstat fake the
     * offsets it uses are origin coordinates. Falls back to the real file
     * when the request exceeds the origin's extent (e.g. a whole-file map
     * of our larger apk). */
    if (fd >= 0 && fd < FD_TABLE_SLOTS && g_fd_flag[fd] && !(map_flags & MAP_ANONYMOUS) &&
        origin_ensure() && (long long)offset + (long long)length <= g_origin_size) {
        void* result = g_real_mmap(addr, length, prot, map_flags, g_origin_fd, offset);
        int saved = errno;
        if (result != MAP_FAILED) {
            if (LOG_BUDGET(g_mmap_redirects, 16))
                emit("mmap fd=%d len=%#zx off=%#llx -> origin-fd = %p", fd, length,
                     (unsigned long long)offset, result);
            return result;
        }
        emit("mmap origin redirect failed fd=%d len=%#zx off=%#llx errno=%d", fd, length,
             (unsigned long long)offset, saved);
    }
    /* Silent for everything else: ART mmaps base.apk constantly for
     * dex/resources and the shell never does through hooked GOTs. */
    return g_real_mmap(addr, length, prot, map_flags, fd, offset);
}

static int my_close(int fd) {
    if (!g_real_close) return -1;
    if (fd >= 0 && fd < FD_TABLE_SLOTS && g_fd_flag[fd]) {
        emit("close fd=%d from=\"%s\"", fd, describe_fd(fd));
        clear_flag_fd(fd);
    }
    if (g_in_hook) return g_real_close(fd);
    g_in_hook = 1;
    remember_fd(fd, NULL);
    int rc = g_real_close(fd);
    g_in_hook = 0;
    return rc;
}

