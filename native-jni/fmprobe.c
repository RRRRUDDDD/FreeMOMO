/* fd-based size query. Flagged fds report the ORIGIN apk size: the shell
 * derives every offset it reads from this number, so faking it keeps the
 * whole session in origin coordinates and the identity redirect maps every
 * subsequent read correctly. g_fd_size flips with it, so serve_tail's
 * end-relative branch then resolves origin-coords windows too. Only
 * flagged fds are touched. Not on the observing chassis: it must stay
 * re-entrant (no g_in_hook flip) because it runs inside libc's own stat
 * paths, and it restores nothing. */
static int my_fstat(int fd, struct stat* st) {
    if (g_in_hook || !g_real_fstat) return g_real_fstat ? g_real_fstat(fd, st) : -1;
    int rc = g_real_fstat(fd, st);
    if (rc != 0 || !st || fd < 0 || fd >= FD_TABLE_SLOTS || !g_fd_flag[fd]) return rc;
    if (st->st_size != (off_t)kOriginApkSize) {
        st->st_size = (off_t)kOriginApkSize;
        g_fd_size[fd] = kOriginApkSize;
        if (LOG_BUDGET(g_fstat_fakes, 16))
            emit("fstat fd=%d size-> %#llx (origin) from=\"%s\"", fd, kOriginApkSize,
                 describe_fd(fd));
    }
    return rc;
}

