/*
 * dexcore - diagnostic GOT tracer for the SecNeo shell (libmomoco.so) study.
 *
 * Loaded by the LSPatch metaloader stub before any framework or app code.
 * Renamed from libfmprobe to libdexcore to avoid detection by the shell's
 * anti-injection checks. Load tiers, in stub order: apk asset ("base.apk!/
 * assets/...", the same mechanism liblspatch.so uses, so /proc/maps shows the
 * mappings as the apk file itself and nothing lands in nativeLibraryDir),
 * anonymous memfd ("/memfd:jit-cache (deleted)"), then file-backed
 * System.loadLibrary only for candidates that still ship the jniLib entry.
 * hide_self_mapping renames the file-backed mapping via prctl when the last
 * tier runs.
 *
 * Phase 1 (early, low footprint) interposes dlopen/android_dlopen_ext only
 * in every eligible loaded library — no file hooks, so the Java IO native
 * layer remains untouched during the shell's APK read sequence.
 *
 * Phase R (round r10/r11, early, libjavacore only) turns the tracer into a
 * read REDIRECTOR. Round-06 evidence fixed the shell's APK validation
 * fingerprint: through libjavacore's GOT it does lseek(size-0x80)+read 128,
 * lseek(size-0x2a)+read 20, lseek(0)+read 4 — the last window is the final
 * central-directory entry name, "META-INF/MANIFEST.MF" on a v1-signed apk —
 * and a later stage adds lseek(4)+read 20 (first local file header fields).
 * LSPatch repackaged apks (v2/v3 signature, last CD entry = a lib/ asset)
 * fail that read set, the shell's decryption context degrades, and
 * JNI_OnLoad+76 passes garbage strings into JNI (S25 10-16 crash matrix).
 * The redirector flags fds opened for the app's own base.apk path and
 * serves those windows from the genuine original bytes embedded in the
 * library at build time (kOriginHead/kOriginTail, generated from the pinned
 * release). Wider tail windows fall back to the extracted origin apk
 * (cache/lspatch/origin/<hash>.apk) once LSPatch writes it — r10 showed the
 * extraction is NOT yet there during the first-launch check, so the
 * embedded bytes are the primary source. Everything else passes through
 * untouched. Offsets and sizes come from fstat at runtime — nothing to
 * recalibrate per build.
 *
 * Phase 2 (delayed, unchanged) still installs the observation file hooks on
 * libjavacore/libziparchive/libandroidfw AFTER momoco is dlopened or on a
 * fallback timer; for libjavacore those slots are already ours, so it only
 * patches libziparchive/libandroidfw.
 *
 * When libmomoco.so is dlopened — before its JNI_OnLoad runs — phase 2
 * rewrites the new library's GOT so every file access it performs logs path,
 * arguments and result. Evidence goes to a TCP log channel and a fallback
 * file.
 */
