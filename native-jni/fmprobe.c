static void emit_line(const char* line, size_t len) {
    if (g_log_fd >= 0) {
        ssize_t written = write(g_log_fd, line, len);
        (void)written;
    }
    if (g_log_sock >= 0) {
        ssize_t sent = send(g_log_sock, line, len, MSG_NOSIGNAL);
        (void)sent;
    }
}

static void emit(const char* fmt, ...) {
    char line[640];
    char* end = line + sizeof(line) - 1;
    char* p = line + snprintf(line, (size_t)(end - line), "%lld ", mono_us());
    if (p > end) p = end;
    va_list ap;
    va_start(ap, fmt);
    vsnprintf(p, (size_t)(end - p), fmt, ap);
    va_end(ap);
    size_t len = strlen(line);
    line[len++] = '\n';
    if ((g_log_fd >= 0 || g_log_sock >= 0)) {
        emit_line(line, len);
    } else if (g_pending_len + len <= sizeof(g_pending)) {
        memcpy(g_pending + g_pending_len, line, len);
        g_pending_len += len;
    } else {
        g_pending_drops++;
    }
    /* Events buffer only: the probe-device-run evidence scripts grep DEXCORE
     * from `logcat -d -b events`; the main-buffer duplicate doubled logd
     * traffic for no reader. */
    __android_log_buf_write(LOG_ID_EVENTS, ANDROID_LOG_INFO, PROBE_TAG, line);
}

static void flush_pending(void) {
    if (g_pending_len == 0) return;
    if (g_log_fd < 0 && g_log_sock < 0) return;
    if (g_pending_drops) {
        char note[80];
        int n = snprintf(note, sizeof(note), "pending drops=%ld\n", g_pending_drops);
        emit_line(note, (size_t)n);
        g_pending_drops = 0;
    }
    emit_line(g_pending, g_pending_len);
    g_pending_len = 0;
}

static void remember_fd(int fd, const char* path) {
    if (fd < 0 || fd >= FD_TABLE_SLOTS) return;
    char* slot = g_fd_path[fd];
    if (!path) {
        slot[0] = '\0';
        return;
    }
    size_t n = strlen(path);
    if (n >= FD_PATH_MAX) n = FD_PATH_MAX - 1;
    memcpy(slot, path, n);
    slot[n] = '\0';
}

static const char* describe_fd(int fd) {
    if (fd >= 0 && fd < FD_TABLE_SLOTS && g_fd_path[fd][0]) return g_fd_path[fd];
    return "?";
}

/* The app's own base.apk: /data/app/~~…/<pkg>-…/base.apk for the momo
 * package. Opened with an absolute path through libjavacore's open/openat
 * (r6: single `open "…/base.apk" flags=0x80000`). */
static int path_is_base_apk(const char* path) {
    if (!path) return 0;
    size_t n = strlen(path);
    if (n < 9 || strcmp(path + n - 9, "/base.apk") != 0) return 0;
    return strstr(path, "maimemo") != NULL;
}

/* Quiet-mode gate: pass-through calls are logged only when they touch
 * something on the investigation path. Keeps the TCP channel readable while
 * libjavacore serves the whole process's Java IO. */
static int interesting_path(const char* path) {
    if (!path) return 0;
    static const char* const kNeedles[] = {
        "maimemo", "lspatch", "momoco", "dexcore", "base.apk",
    };
    for (size_t i = 0; i < sizeof(kNeedles) / sizeof(kNeedles[0]); ++i) {
        if (strstr(path, kNeedles[i])) return 1;
    }
    return 0;
}

static void clear_flag_fd(int fd) {
    if (fd < 0 || fd >= FD_TABLE_SLOTS) return;
    g_fd_flag[fd] = 0;
    g_fd_pos[fd] = 0;
    g_fd_size[fd] = 0;
    g_fd_ptlog[fd] = 0;
}

/* Called inside the open wrappers (g_in_hook already set) when a fresh fd
 * resolves to the app's base.apk. Records the size, verifies the EOCD sits
 * at size-22 (the end-relative mapping assumes no ZIP comment), and arms
 * the fd. Own libc calls here are real: libdexcore is GOT-hook-excluded. */
static void flag_base_apk_fd(int fd, const char* path) {
    if (fd < 0 || fd >= FD_TABLE_SLOTS) {
        emit("redirect-arm FAILED fd=%d outside table (%s)", fd, path ? path : "?");
        return;
    }
    struct stat st;
    if (fstat(fd, &st) != 0) {
        int saved = errno;
        emit("redirect-arm FAILED fd=%d fstat errno=%d", fd, saved);
        return;
    }
    long long size = (long long)st.st_size;
    if (size < ZIP_MIN_BYTES) {
        emit("redirect-arm FAILED fd=%d size=%lld too small", fd, size);
        return;
    }
    char magic[4] = {0};
    if (pread(fd, magic, 4, (off_t)(size - ZIP_EOCD_LEN)) != 4 ||
        memcmp(magic, ZIP_EOCD_MAGIC, 4) != 0) {
        emit("redirect-arm FAILED fd=%d no EOCD at size-22 (size=%#llx)", fd, size);
        return;
    }
    g_fd_flag[fd] = FDF_REDIRECT;
    g_fd_pos[fd] = 0;
    g_fd_size[fd] = size;
    g_fd_ptlog[fd] = 0;
    emit("redirect-arm fd=%d size=%#llx path=%s", fd, size, path ? path : "?");
}

/* Open one candidate and accept it only when its size matches the official
 * release byte-for-byte (kOriginApkSize) and a clean EOCD sits at size-22.
 * The EOCD check alone cannot tell "EOCD written, content still buffered"
 * from a complete file — only the exact size can. Closes fd on rejection. */
static int origin_try_open(const char* candidate) {
    int fd = open(candidate, O_RDONLY | O_CLOEXEC);
    if (fd < 0) {
        int saved = errno;
        if (g_origin_failures <= ORIGIN_LOG_MAX) {
            emit("redirect-origin open failed %s errno=%d (attempt %d)", candidate, saved,
                 g_origin_failures);
        }
        return 0;
    }
    struct stat st;
    if (fstat(fd, &st) != 0) {
        int saved = errno;
        if (g_origin_failures <= ORIGIN_LOG_MAX) {
            emit("redirect-origin fstat failed %s errno=%d", candidate, saved);
        }
        close(fd);
        return 0;
    }
    long long size = (long long)st.st_size;
    if (size != kOriginApkSize) {
        if (g_origin_failures <= ORIGIN_LOG_MAX) {
            emit("redirect-origin size mismatch %s size=%#llx want=%#llx — skipping", candidate,
                 size, kOriginApkSize);
        }
        close(fd);
        return 0;
    }
    char magic[4] = {0};
    if (pread(fd, magic, 4, (off_t)(size - ZIP_EOCD_LEN)) != 4 ||
        memcmp(magic, ZIP_EOCD_MAGIC, 4) != 0) {
        if (g_origin_failures <= ORIGIN_LOG_MAX) {
            emit("redirect-origin %s has no EOCD at size-22 — refusing (commented zip?)",
                 candidate);
        }
        close(fd);
        return 0;
    }
    g_origin_fd = fd;
    g_origin_size = size;
    snprintf(g_origin_path, sizeof(g_origin_path), "%s", candidate);
    emit("redirect-origin armed path=%s size=%#llx", g_origin_path, g_origin_size);
    return 1;
}

/* Locate and open the extracted origin apk (byte-identical to the official
 * release). LSPatch names it <hash>.apk under cache/lspatch/origin/, the
 * hash varying with the origin build, so scan the directory instead of
 * hardcoding. Candidate order: our own dexcore-extract.apk first (exact
 * name), then any *.apk in the directory, then the one hash name actually
 * observed on our test tablets. Every candidate passes the same size gate
 * in origin_try_open — a wrong-size apk picked up by the scan would feed
 * tampered bytes straight into the shell's integrity checks. This is only
 * the FALLBACK source — the embedded original head/tail bytes cover every
 * observed check window and have no extraction timing dependency. Retries
 * are rate-limited to one attempt per 50 ms with only the first three
 * failures logged (r10 evidence: the extraction lands some time after the
 * shell's first-launch check, so a permanent failure cap would disable the
 * fallback for the whole process). Returns 1 with g_origin_fd/size/path
 * populated, 0 on failure. */
static int origin_ensure(void) {
    if (g_origin_fd >= 0) return 1;
    long long now = mono_us();
    if (now - g_origin_last_attempt_us < 50000) return 0;
    g_origin_last_attempt_us = now;
    g_origin_failures++;
    static const char* const kOriginDir =
        "/data/user/0/com.maimemo.android.momo/cache/lspatch/origin";
    char candidate[256];
    int found = 0;
    int rc = snprintf(candidate, sizeof(candidate), "%s/dexcore-extract.apk", kOriginDir);
    if (rc > 0 && rc < (int)sizeof(candidate)) found = origin_try_open(candidate);
    if (!found) {
        DIR* d = opendir(kOriginDir);
        if (d) {
            struct dirent* e;
            while ((e = readdir(d)) != NULL && !found) {
                size_t n = strlen(e->d_name);
                if (n < 5 || n >= sizeof(candidate) || strcmp(e->d_name + n - 4, ".apk") != 0)
                    continue;
                int rc2 = snprintf(candidate, sizeof(candidate), "%s/%s", kOriginDir, e->d_name);
                if (rc2 > 0 && rc2 < (int)sizeof(candidate)) found = origin_try_open(candidate);
            }
            closedir(d);
        }
    }
    if (!found) {
        /* The one name actually observed on our test tablets (r4-era
         * tombstones: cache/lspatch/origin/841874081.apk, 83.6MB,
         * byte-identical to the official release) — covers the case where
         * the directory listing fails but the file is there. Same size
         * gate as every other candidate. */
        int rc3 = snprintf(candidate, sizeof(candidate), "%s/841874081.apk", kOriginDir);
        if (rc3 > 0 && rc3 < (int)sizeof(candidate)) found = origin_try_open(candidate);
    }
    return found;
}

/* Register a library's executable range for fd-flag caller attribution.
 * Registration happens at phase R (libjavacore) and at every new dlopen
 * (DexHelper, momoco), so only shell-side opens are ever flagged. */
static void register_hooked_lib(uintptr_t base, size_t size, const char* name) {
    if (g_hooked_libs_count >= HOOKED_LIBS_MAX) return;
    for (int i = 0; i < g_hooked_libs_count; ++i) {
        if (g_hooked_libs[i].base == base) return;
    }
    lib_range* r = &g_hooked_libs[g_hooked_libs_count++];
    r->base = base;
    r->end = base + size;
    snprintf(r->name, sizeof(r->name), "%s", name);
}

static int caller_is_hooked_lib(void* ret) {
    uintptr_t pc = (uintptr_t)ret;
    if (!pc) return 0;
    for (int i = 0; i < g_hooked_libs_count; ++i) {
        if (pc >= g_hooked_libs[i].base && pc < g_hooked_libs[i].end) return 1;
    }
    return 0;
}

/* Serve a redirect decision for a flagged fd. Returns the byte count served
 * (>= 0), or -2 when the read must pass through to the real file instead.
 * Sources, in order:
 *   1. embedded original head bytes (offset 0..ORIGIN_HEAD_LEN);
 *   2. our-coords tail window, end-relative (the shell computed offsets from
 *      our real fstat size before the fake took effect);
 *   3. embedded original central-directory region [kOriginCdOff, apk end)
 *      — r13 evidence: with the fstat fake the shell walks the ENTIRE CD
 *      in origin coordinates through the served EOCD fields;
 *   4. identity map onto the extracted origin apk for everything else
 *      (payload dex data, local headers) — the synchronous pre-extraction
 *      in dexcore's JNI_OnLoad guarantees the file exists before the
 *      shell's first read. */
static ssize_t serve_tail(int fd, void* buf, size_t count, long long x, const char* what) {
    if (!g_fd_flag[fd]) return -2;
    if (x >= 0 && x < (long long)ORIGIN_HEAD_LEN &&
        x + (long long)count <= (long long)ORIGIN_HEAD_LEN) {
        memcpy(buf, kOriginHead + x, count);
        emit("redirect %s fd=%d x=%#llx n=%zu -> head-embed[%#llx] = %zu", what, fd, x, count, x,
             count);
        return (ssize_t)count;
    }
    long long y = x;
    int endrel = 0;
    if (g_fd_size[fd] != kOriginApkSize && x >= g_fd_size[fd] - REDIRECT_TAIL_MARGIN &&
        x < g_fd_size[fd]) {
        y = x + (kOriginApkSize - g_fd_size[fd]);
        endrel = 1;
    }
    if (y >= kOriginCdOff && y + (long long)count <= kOriginCdOff + ORIGIN_CD_LEN) {
        memcpy(buf, kOriginCd + (y - kOriginCdOff), count);
        emit("redirect %s fd=%d x=%#llx n=%zu -> cd-embed[%#llx]%s = %zu", what, fd, x, count, y,
             endrel ? " endrel" : "", count);
        return (ssize_t)count;
    }
    if (origin_ensure() && y >= 0 && y + (long long)count <= g_origin_size) {
        ssize_t rc = pread(g_origin_fd, buf, count, (off_t)y);
        int saved = errno;
        emit("redirect %s fd=%d x=%#llx n=%zu -> origin-id[%#llx] = %zd from=%s%s", what, fd, x,
             count, y, rc, g_origin_path, err_suffix(rc >= 0, saved));
        errno = saved;
        if (rc >= 0) return rc;
        return -2;
    }
    if (LOG_BUDGET(g_fd_ptlog[fd], REDIRECT_PTLOG_MAX))
        emit("redirect-skip %s fd=%d x=%#llx n=%zu (no source)", what, fd, x, count);
    return -2;
}

static int refresh_maps(void) {
    int fd = open("/proc/self/maps", O_RDONLY | O_CLOEXEC);
    if (fd < 0) return -1;
    g_maps_len = 0;
    while (g_maps_len + 1 < sizeof(g_maps)) {
        ssize_t n = read(fd, g_maps + g_maps_len, sizeof(g_maps) - 1 - g_maps_len);
        if (n <= 0) break;
        g_maps_len += (size_t)n;
    }
    close(fd);
    g_maps[g_maps_len] = '\0';
    return 0;
}

/* Lowest READABLE mapping start whose pathname ends with /<basename>. The
 * matched pathname is copied (line-bounded) into path_buf when found.
 * Non-readable off==0 reservations (linker placeholders) must be skipped:
 * patching them yields "not a mapped ELF" and misses the real library
 * (r12: libDexHelper.so file_hooks=-1). */
static void* find_lib_base(const char* name, char* path_buf, size_t path_size) {
    const char* slash = strrchr(name, '/');
    const char* base_name = slash ? slash + 1 : name;
    char pattern[192];
    snprintf(pattern, sizeof(pattern), "/%s", base_name);
    void* best = NULL;
    char buf[192];
    const char* p = g_maps;
    while (p && *p) {
        const char* eol = strchr(p, '\n');
        if (!eol) break;
        map_line ml;
        if (parse_map_line(p, &ml) >= 4) {
            if (ml.off == 0 && ml.perms[0] == 'r' && ml.path && *ml.path && *ml.path != '[') {
                line_copy(ml.path, eol, buf, sizeof(buf));
                if (strstr(buf, pattern)) {
                    if (!best || (void*)(uintptr_t)ml.start < best) {
                        best = (void*)(uintptr_t)ml.start;
                        if (path_buf && path_size) line_copy(ml.path, eol, path_buf, path_size);
                    }
                }
            }
        }
        p = eol + 1;
    }
    return best;
}

/* Lowest mapping start and highest end across all mappings of <name> (the
 * library's full extent, for caller-attribution ranges). */
static void* find_lib_extent(const char* name, void** out_end) {
    const char* slash = strrchr(name, '/');
    const char* base_name = slash ? slash + 1 : name;
    char pattern[192];
    snprintf(pattern, sizeof(pattern), "/%s", base_name);
    void* first = NULL;
    uintptr_t last_end = 0;
    char buf[192];
    const char* p = g_maps;
    while (p && *p) {
        const char* eol = strchr(p, '\n');
        if (!eol) break;
        map_line ml;
        /* Same fields as find_lib_base: address range, perms and offset must
         * all convert (the old inline sscanf suppressed perms, so its >= 3
         * count maps to >= 4 here). */
        if (parse_map_line(p, &ml) >= 4) {
            if (ml.path && *ml.path && *ml.path != '[') {
                line_copy(ml.path, eol, buf, sizeof(buf));
                if (strstr(buf, pattern)) {
                    if (!first || (void*)(uintptr_t)ml.start < first)
                        first = (void*)(uintptr_t)ml.start;
                    if ((uintptr_t)ml.end > last_end) last_end = ml.end;
                }
            }
        }
        p = eol + 1;
    }
    if (out_end) *out_end = (void*)last_end;
    return first;
}

/* Protection flags of the mapping holding addr, 0 when no maps line covers
 * it. The 0 for "unknown" is deliberate: the old default pretended unknown
 * pages were RW, which (a) let the phaseR/phase2/phase2d readability gates
 * pass vacuously and GOT patching run against a base the maps snapshot
 * never verified (stale snapshot, late dlopen), and (b) "restored" an
 * unverifiable page to RW after the patch write. Unknown now fails closed:
 * the gates skip, and the patch path simply does not restore a prot it
 * could not observe (the page already sits at the RW the write needed,
 * exactly as before). */
static int prot_for_addr(void* addr) {
    unsigned long long a = (unsigned long long)(uintptr_t)addr;
    const char* p = g_maps;
    while (p && *p) {
        const char* eol = strchr(p, '\n');
        if (!eol) break;
        map_line ml;
        if (parse_map_line(p, &ml) >= 3 && a >= ml.start && a < ml.end) {
            int prot = 0;
            if (ml.perms[0] == 'r') prot |= PROT_READ;
            if (ml.perms[1] == 'w') prot |= PROT_WRITE;
            if (ml.perms[2] == 'x') prot |= PROT_EXEC;
            return prot;
        }
        p = eol + 1;
    }
    return 0;
}

/* Shared relocation walk once the dynamic table address is known. Every
 * derived address must land inside [base, lib_end): a scrubbed or tampered
 * header would otherwise turn the walk into wild reads, and a bogus
 * r_offset into a wild GOT write — both fatal inside the host process. */
static int patch_got_dyn(void* base, Elf64_Dyn* dyn, const hook_entry* hooks, int hook_count,
                         const char* label, int dump_imports, int* import_count, void* lib_end) {
    const char* lo = (const char*)base;
    const char* hi = (const char*)lib_end;
    if (!hi || hi <= lo) return -1;
    Elf64_Addr imgsz = (Elf64_Addr)(size_t)(hi - lo);
    Elf64_Addr jmprel = 0, rela = 0, symtab_addr = 0, strtab_addr = 0;
    Elf64_Xword pltrelsz = 0, relasz = 0, pltrel = 0, strsz = 0;
    int guard = 0;
    for (Elf64_Dyn* d = dyn;
         (const char*)(d + 1) <= hi && d->d_tag != DT_NULL && guard++ < 512; ++d) {
        switch (d->d_tag) {
            case DT_JMPREL: jmprel = d->d_un.d_ptr; break;
            case DT_PLTRELSZ: pltrelsz = d->d_un.d_val; break;
            case DT_PLTREL: pltrel = d->d_un.d_val; break;
            case DT_RELA: rela = d->d_un.d_ptr; break;
            case DT_RELASZ: relasz = d->d_un.d_val; break;
            case DT_SYMTAB: symtab_addr = d->d_un.d_ptr; break;
            case DT_STRTAB: strtab_addr = d->d_un.d_ptr; break;
            case DT_STRSZ: strsz = d->d_un.d_val; break;
            default: break;
        }
    }
    /* No symtab/strtab/strsz means no names to match against; treat it the
     * same as an unreadable header instead of dereferencing base+0. */
    if (!symtab_addr || !strtab_addr || !strsz || symtab_addr >= imgsz ||
        strtab_addr >= imgsz || strtab_addr > imgsz - strsz) {
        return -1;
    }
    Elf64_Sym* symtab = (Elf64_Sym*)(lo + symtab_addr);
    const char* strtab = lo + strtab_addr;
    const char* strtab_end = strtab + strsz;
    int patched = 0, imports = 0;

    struct {
        Elf64_Addr addr;
        Elf64_Xword size;
    } tables[2];
    tables[0].addr = jmprel;
    tables[0].size = (pltrel == DT_RELA) ? pltrelsz : 0;
    tables[1].addr = rela;
    tables[1].size = relasz;
    for (int t = 0; t < 2; ++t) {
        if (tables[t].addr > imgsz || tables[t].size > imgsz - tables[t].addr) {
            tables[t].size = 0; /* relocation table outside the image: refuse to walk it */
            continue;
        }
        for (Elf64_Xword off = 0; off + sizeof(Elf64_Rela) <= tables[t].size;
             off += sizeof(Elf64_Rela)) {
            Elf64_Rela* r = (Elf64_Rela*)(lo + tables[t].addr + off);
            uint32_t type = (uint32_t)(r->r_info & 0xffffffffu);
            uint32_t sym = (uint32_t)(r->r_info >> 32);
            if (type != R_AARCH64_JUMP_SLOT && type != R_AARCH64_GLOB_DAT) continue;
            const Elf64_Sym* se = symtab + sym;
            if ((const char*)se < lo || (const char*)(se + 1) > hi) continue;
            if ((Elf64_Xword)se->st_name >= strsz) continue;
            const char* name = strtab + se->st_name;
            /* strcmp may only run once the name is NUL-terminated inside the
             * string table; an unterminated entry would read past strsz. */
            if (!memchr(name, 0, (size_t)(strtab_end - name))) continue;
            imports++;
            if (dump_imports) emit("import %s %s", label, name);
            for (int h = 0; h < hook_count; ++h) {
                if (strcmp(name, hooks[h].name) != 0) continue;
                if (r->r_offset > imgsz - sizeof(void*)) continue;
                void** slot = (void**)(lo + r->r_offset);
                if (*slot == hooks[h].wrapper) break;
                *hooks[h].real_slot = *slot;
                uintptr_t page = (uintptr_t)slot & ~(uintptr_t)(g_pagesize - 1);
                int oldprot = prot_for_addr((void*)page);
                if (mprotect((void*)page, (size_t)g_pagesize, PROT_READ | PROT_WRITE) == 0) {
                    *slot = hooks[h].wrapper;
                    if (oldprot) mprotect((void*)page, (size_t)g_pagesize, oldprot);
                    patched++;
                } else {
                    emit("mprotect failed %s %s errno=%d", label, name, errno);
                }
                break;
            }
        }
    }
    if (import_count) *import_count = imports;
    return patched;
}

/* Memory-header variant (fine for system libs whose headers stay intact). */
static int patch_got(void* base, const hook_entry* hooks, int hook_count, const char* label,
                     int dump_imports, int* import_count, void* lib_end) {
    if (!lib_end || (char*)lib_end <= (char*)base) return -1;
    Elf64_Ehdr* eh = (Elf64_Ehdr*)base;
    if (memcmp(eh->e_ident, ELFMAG, SELFMAG) != 0 || eh->e_ident[EI_CLASS] != ELFCLASS64) {
        return -1;
    }
    /* A path-matched mapping is not always a sane ELF load bias; refuse
     * anything whose header layout could send reads outside the image. */
    if (eh->e_type != ET_DYN || eh->e_phoff < sizeof(Elf64_Ehdr) ||
        eh->e_phoff > (Elf64_Off)1 << 20 || eh->e_phnum == 0 || eh->e_phnum > 96 ||
        eh->e_phentsize != sizeof(Elf64_Phdr)) {
        return -1;
    }
    Elf64_Addr imgsz = (Elf64_Addr)(size_t)((char*)lib_end - (char*)base);
    if (eh->e_phoff + (Elf64_Off)eh->e_phnum * sizeof(Elf64_Phdr) > (Elf64_Off)imgsz) {
        return -1;
    }
    Elf64_Phdr* ph = (Elf64_Phdr*)((char*)base + eh->e_phoff);
    Elf64_Dyn* dyn = NULL;
    for (int i = 0; i < eh->e_phnum; ++i) {
        if (ph[i].p_type == PT_DYNAMIC) {
            /* p_vaddr must land inside the mapped extent; a bogus value would
             * otherwise be dereferenced by the relocation walk. */
            if (ph[i].p_vaddr < imgsz && imgsz - ph[i].p_vaddr >= sizeof(Elf64_Dyn)) {
                dyn = (Elf64_Dyn*)((char*)base + ph[i].p_vaddr);
            }
            break;
        }
    }
    if (!dyn) return -1;
    return patch_got_dyn(base, dyn, hooks, hook_count, label, dump_imports, import_count,
                         lib_end);
}

/* vaddr -> file offset through the PT_LOAD table; NULL when unmapped. */
static const unsigned char* seg_at(const unsigned char* img, const Elf64_Phdr* ph, int phnum,
                                   Elf64_Addr vaddr, size_t len) {
    for (int i = 0; i < phnum; ++i) {
        if (ph[i].p_type != PT_LOAD) continue;
        if (vaddr >= ph[i].p_vaddr && vaddr + len <= ph[i].p_vaddr + ph[i].p_filesz) {
            return img + ph[i].p_offset + (vaddr - ph[i].p_vaddr);
        }
    }
    return NULL;
}

/* File-header variant. Hardened libs wipe their in-memory ELF headers AND
 * dynamic tables from their own init constructors (anti-dump; r16 evidence:
 * libDexHelper.so imports=0 with an intact file), so parse EVERYTHING from
 * the on-disk image: ehdr/phdrs/dynamic/relocations/symbols, resolving
 * vaddrs to file offsets through the PT_LOAD table. Only the final GOT
 * slot write touches memory. file_path must be a real extracted file. */
static int patch_got_file(void* base, const char* file_path, const hook_entry* hooks,
                          int hook_count, const char* label, int dump_imports,
                          int* import_count) {
    int fd = open(file_path, O_RDONLY | O_CLOEXEC);
    if (fd < 0) return -1;
    struct stat st;
    if (fstat(fd, &st) != 0 || st.st_size < (off_t)sizeof(Elf64_Ehdr) || st.st_size > 64 << 20) {
        close(fd);
        return -1;
    }
    size_t fsize = (size_t)st.st_size;
    unsigned char* img = malloc(fsize);
    if (!img) {
        close(fd);
        return -1;
    }
    ssize_t total = 0;
    while (total < (ssize_t)fsize) {
        ssize_t n = pread(fd, img + total, fsize - (size_t)total, (off_t)total);
        if (n <= 0) break;
        total += n;
    }
    close(fd);
    if (total < (ssize_t)sizeof(Elf64_Ehdr)) {
        free(img);
        return -1;
    }
    Elf64_Ehdr eh;
    memcpy(&eh, img, sizeof(eh));
    if (memcmp(eh.e_ident, ELFMAG, SELFMAG) != 0 || eh.e_ident[EI_CLASS] != ELFCLASS64 ||
        eh.e_type != ET_DYN || eh.e_phoff < sizeof(Elf64_Ehdr) ||
        eh.e_phoff > (Elf64_Off)1 << 20 || eh.e_phnum == 0 || eh.e_phnum > 96 ||
        eh.e_phentsize != sizeof(Elf64_Phdr) ||
        (size_t)total < eh.e_phoff + (size_t)eh.e_phnum * sizeof(Elf64_Phdr)) {
        free(img);
        return -1;
    }
    Elf64_Phdr* ph = (Elf64_Phdr*)(img + eh.e_phoff);

    Elf64_Phdr* dyn_ph = NULL;
    for (int i = 0; i < eh.e_phnum; ++i) {
        if (ph[i].p_type == PT_DYNAMIC) {
            dyn_ph = &ph[i];
            break;
        }
    }
    if (!dyn_ph || dyn_ph->p_filesz == 0 || dyn_ph->p_filesz > 64 * 1024) {
        free(img);
        return -1;
    }
    const unsigned char* dyn_img = seg_at(img, ph, eh.e_phnum, dyn_ph->p_vaddr, dyn_ph->p_filesz);
    if (!dyn_img) {
        free(img);
        return -1;
    }
    Elf64_Addr jmprel = 0, rela = 0, symtab_addr = 0, strtab_addr = 0;
    Elf64_Xword pltrelsz = 0, relasz = 0, pltrel = 0;
    const Elf64_Dyn* d = (const Elf64_Dyn*)dyn_img;
    size_t dyn_count = dyn_ph->p_filesz / sizeof(Elf64_Dyn);
    for (size_t i = 0; i < dyn_count && d[i].d_tag != DT_NULL; ++i) {
        switch (d[i].d_tag) {
            case DT_JMPREL: jmprel = d[i].d_un.d_ptr; break;
            case DT_PLTRELSZ: pltrelsz = d[i].d_un.d_val; break;
            case DT_PLTREL: pltrel = d[i].d_un.d_val; break;
            case DT_RELA: rela = d[i].d_un.d_ptr; break;
            case DT_RELASZ: relasz = d[i].d_un.d_val; break;
            case DT_SYMTAB: symtab_addr = d[i].d_un.d_ptr; break;
            case DT_STRTAB: strtab_addr = d[i].d_un.d_ptr; break;
            default: break;
        }
    }
    const char* strtab = (const char*)seg_at(img, ph, eh.e_phnum, strtab_addr, 1);
    if (!strtab) {
        free(img);
        return -1;
    }
    int patched = 0, imports = 0;
    struct {
        Elf64_Addr addr;
        Elf64_Xword size;
    } tables[2];
    tables[0].addr = jmprel;
    tables[0].size = (pltrel == DT_RELA) ? pltrelsz : 0;
    tables[1].addr = rela;
    tables[1].size = relasz;
    for (int t = 0; t < 2; ++t) {
        for (Elf64_Xword off = 0; off + sizeof(Elf64_Rela) <= tables[t].size;
             off += sizeof(Elf64_Rela)) {
            const unsigned char* rent =
                seg_at(img, ph, eh.e_phnum, tables[t].addr + off, sizeof(Elf64_Rela));
            if (!rent) break;
            Elf64_Rela r;
            memcpy(&r, rent, sizeof(r));
            uint32_t type = (uint32_t)(r.r_info & 0xffffffffu);
            uint32_t sym = (uint32_t)(r.r_info >> 32);
            if (type != R_AARCH64_JUMP_SLOT && type != R_AARCH64_GLOB_DAT) continue;
            const unsigned char* sent = seg_at(img, ph, eh.e_phnum,
                                               symtab_addr + (Elf64_Addr)sym * sizeof(Elf64_Sym),
                                               sizeof(Elf64_Sym));
            if (!sent) continue;
            Elf64_Sym s;
            memcpy(&s, sent, sizeof(s));
            const char* name = strtab + s.st_name;
            if ((size_t)(name - strtab) > fsize) continue;
            imports++;
            if (dump_imports) emit("import %s %s", label, name);
            for (int h = 0; h < hook_count; ++h) {
                if (strcmp(name, hooks[h].name) != 0) continue;
                void** slot = (void**)((char*)base + r.r_offset);
                if (*slot == hooks[h].wrapper) break;
                *hooks[h].real_slot = *slot;
                uintptr_t page = (uintptr_t)slot & ~(uintptr_t)(g_pagesize - 1);
                int oldprot = prot_for_addr((void*)page);
                if (mprotect((void*)page, (size_t)g_pagesize, PROT_READ | PROT_WRITE) == 0) {
                    *slot = hooks[h].wrapper;
                    if (oldprot) mprotect((void*)page, (size_t)g_pagesize, oldprot);
                    patched++;
                } else {
                    emit("mprotect failed %s %s errno=%d", label, name, errno);
                }
                break;
            }
        }
    }
    if (import_count) *import_count = imports;
    free(img);
    return patched;
}

/* ---- wrapper chassis for the observing (non-redirecting) hooks ----
 * Every wrapper below shares one prologue/epilogue: an optional pre-call
 * statement (variadic mode extraction, the delayed-hook timeout check), a
 * re-entrancy/pre-init guard that delegates untouched, the real call under
 * the g_in_hook guard with errno saved, a wrapper-specific body, then errno
 * restore and guard drop. The body sees rc/saved; emit formats are
 * transcribed verbatim so the probe log stays byte-identical.
 * The redirecting wrappers keep their hand-written chassis: my_read and the
 * pread family, my_lseek, my_mmap, my_close (fd-flag logic, shadow-position
 * bookkeeping and errno flows that do not fit), and my_fstat, which must
 * stay re-entrant and therefore never flips the guard. */
#define PROBE_HOOK(ret_t, name, fail, sig, args, precall, body)              \
    static ret_t my_##name sig {                                             \
        precall;                                                             \
        if (g_in_hook || !g_real_##name)                                     \
            return g_real_##name ? g_real_##name args : fail;                \
        g_in_hook = 1;                                                       \
        ret_t rc = g_real_##name args;                                       \
        int saved = errno;                                                   \
        body;                                                                \
        errno = saved;                                                       \
        g_in_hook = 0;                                                       \
        return rc;                                                           \
    }

